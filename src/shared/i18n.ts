export const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, "zh-CN": zh };
export function translate(language: Language, key: TranslationKey, ...args: Array<string | number>): string {
  return dictionaries[language][key].replace(/\{(\d+)\}/g, (match, index: string) => String(args[Number(index)] ?? match));
}
