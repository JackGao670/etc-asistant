export type Language = "en" | "zh-CN";
export type LanguageSetting = "auto" | Language;
export function resolveLanguage(setting: string, vscodeLanguage: string): Language {
  if (setting === "en" || setting === "zh-CN") return setting;
  return /^zh(?:-|$)/i.test(vscodeLanguage) ? "zh-CN" : "en";
}

